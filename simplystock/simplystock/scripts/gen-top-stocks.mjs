function main() {
  const krStocksPath = path.join(ROOT, "..", "..", "data", "krStocks.json");
  if (!fs.existsSync(krStocksPath)) {
    console.error("krStocks.json을 찾을 수 없습니다:", krStocksPath);
    process.exit(1);
  }

  const krStocks = JSON.parse(fs.readFileSync(krStocksPath, "utf-8"));
  const symbolMap = new Map();
  for (const s of krStocks) {
    const code = s.s.split(".")[0];
    symbolMap.set(code, s);
  }

  const result = [];
  const missing = [];

  for (const [code, sector] of TOP_STOCKS) {
    const kr = symbolMap.get(code);
    if (!kr) {
      missing.push(code);
      continue;
    }
    const marketSuffix = kr.s.includes(".KQ") ? "KQ" : "KS";
    result.push({
      code,
      symbol: `${code}.${marketSuffix}`,
      name: kr.n,
      market: kr.m === "Q" ? "KOSDAQ" : "KOSPI",
      sector,
    });
  }

  if (missing.length > 0) {
    console.warn(`경고: krStocks.json에서 찾지 못한 종목 ${missing.length}개:`, missing.join(", "));
  }

  const outPath = path.join(ROOT, "data", "stockList.json");
  fs.writeFileSync(outPath, JSON.stringify(result, null, 2) + "\n");
  console.log(`stockList.json: ${result.length}개 종목 생성 (대상 ${TOP_STOCKS.length}개 중)`);
}

main();
